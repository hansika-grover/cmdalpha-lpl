"""Fill the results section of README.md from results/metrics.json (never typed by hand)."""
from __future__ import annotations

import json
from pathlib import Path

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
LABEL = {"threshold_100k": "$100k threshold rule", "threshold_50k": "$50k threshold rule", "threshold_25k": "$25k threshold rule",
         "expert_checklist": "Expert rule checklist (no notes)", "money_only": "Money movement only (engine A)",
         "rules_plus_keyword_notes": "Engines A + B + keyword notes", "sentinel": "**Sentinel**",
         "ablation_no_notes": "Sentinel without notes", "ablation_no_sequences": "Sentinel without sequences",
         "ablation_no_money": "Sentinel without money movement"}
TYP = {"investment_romance_scam": "Investment, crypto or romance", "tech_support_impersonation": "Tech support / bank impersonation",
       "government_impersonation": "Government impersonation", "silent_account_takeover": "Silent account takeover",
       "grandparent_voice_clone": "Grandparent / voice clone", "trusted_person_theft": "Trusted-person theft"}


def p(m, d=0):
    v = m["value"] if isinstance(m, dict) else m
    return "–" if v is None else f"{v * 100:.{d}f}%"


def ci(m):
    return f"{m['ci95'][0] * 100:.0f}–{m['ci95'][1] * 100:.0f}%" if m.get("ci95") else ""


def render(r: dict, seeds: dict | None) -> str:
    M, MW = r["methods"], r["matched_workload_100k"]
    reader = "Claude notes reader" if r["meta"]["notes_reader"] == "llm" else "keyword notes reader (Claude reader not yet run)"
    out = [f"Test split: {r['meta']['households']['test']:,} households never seen in training. Notes reader: {reader}. "
           f"95% confidence intervals from household bootstrap. Generated by `make eval readme`.", "",
           f"**Same reviewer workload as the $100k rule** ({MW['weekly_rate'] * 100:.2f}% of households per week):", "",
           "| Method | Cases caught | 95% CI | Caught before money left | Dollars protected | Look-alike false alarms | Precision at 0.5% base rate |",
           "|---|---|---|---|---|---|---|"]
    for k in ("threshold_100k", "expert_checklist", "money_only", "sentinel"):
        m = MW[k]
        out.append(f"| {LABEL[k]} | {p(m['recall'], 1)} | {ci(m['recall'])} | {p(m['caught_before_money_left'], 1)} | "
                   f"{p(m['dollars_protected_share'], 1)} | {p(m['lookalike_false_alarm_rate'], 1)} | {p(m['precision_at_0.5pct_base_rate'], 1)} |")
    out += ["", "**At fixed weekly review budgets** (cases caught, with look-alike false alarms in brackets):", "",
            "| Method | 0.1% | 0.25% | 1% |", "|---|---|---|---|"]
    for k in ("threshold_100k", "threshold_25k"):
        m = M[k]["natural"]
        out.append(f"| {LABEL[k]} (fixed, {m['alerts_per_1k_households_per_week']['value']:.2f} alerts per 1k households a week) | "
                   f"{p(m['recall'])} ({p(m['lookalike_false_alarm_rate'])}) | | |")
    for k in [k for k in LABEL if k in M and "budgets" in M[k]]:
        b = M[k]["budgets"]
        out.append(f"| {LABEL[k]} | " + " | ".join(f"{p(b[x]['recall'])} ({p(b[x]['lookalike_false_alarm_rate'])})" for x in ("0.1%", "0.25%", "1%")) + " |")
    s = M["sentinel"]["budgets"]["0.25%"]
    loto = r.get("leave_one_typology_out", {})
    out += ["", "**By scam type** at a 0.25% budget, and with that type held out of training entirely:", "",
            "| Typology | Test cases | Sentinel | Sentinel, type never seen | $100k rule |", "|---|---|---|---|---|"]
    for t, name in TYP.items():
        bt = s["by_typology"].get(t, {})
        lo = loto.get(t, {})
        out.append(f"| {name} | {bt.get('n', 0)} | {p(bt.get('recall'))} | {p(lo.get('sentinel_recall', {}).get('0.25%'))} | {p(lo.get('threshold_100k_recall'))} |")
    fair = s["fairness_by_age_band"]
    out += ["", "**Calibration:** expected calibration error " + str(r["calibration"]["ece"]) + ". "
            "**Fairness** (false-alarm rate relative to overall, target ≤ 1.25×): "
            + ", ".join(f"ages {k} {v['ratio_to_overall']:.2f}×" for k, v in fair.items()) + ". "
            f"**Speed:** {r['cost']['ms_per_household_scored']} ms per household for all three engines on a laptop."]
    rob = r.get("robustness")
    if rob:
        out += ["", "**Robustness** (same model and thresholds, cases caught at 0.25%): "
                + ", ".join(f"{n} {p(rob[k]['0.25%']['recall'])}" for k, n in
                            [("baseline", "as evaluated"), ("no_notes", "all notes removed"), ("half_notes", "half the notes removed"),
                             ("noisy_account_events", "doubled account-event noise")] if k in rob)
                + f"; coached cover stories {p(rob['coached_cover_story_at_0.25%']['recall'])} (n={rob['coached_cover_story_at_0.25%']['n']})."]
    if seeds:
        sr = seeds["methods"]["sentinel"]["0.25%"]["recall"]
        out += ["", f"**Stability across {len(seeds['seeds'])} independently generated worlds:** Sentinel catches "
                f"{sr['mean'] * 100:.0f}% of cases at 0.25% on average (range {sr['min'] * 100:.0f}–{sr['max'] * 100:.0f}%)."]
    for f, label in (("results/notes_reader_usage.json", "Notes reader"), ("results/case_agent_usage.json", "Case agent")):
        if Path(f).exists():
            u = json.loads(Path(f).read_text())
            out.append(f"\n**{label} usage:** {json.dumps(u)}")
    return "\n".join(out)


def main():
    r = json.loads(Path("results/metrics.json").read_text())
    seeds = json.loads(Path("results/seeds.json").read_text()) if Path("results/seeds.json").exists() else None
    readme = Path("README.md").read_text(encoding="utf-8")
    i, j = readme.index(START) + len(START), readme.index(END)
    Path("README.md").write_text(readme[:i] + "\n" + render(r, seeds) + "\n" + readme[j:], encoding="utf-8")
    print("README.md results updated")


if __name__ == "__main__":
    main()
