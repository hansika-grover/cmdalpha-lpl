"""Fill the results section of README.md from results/metrics.json (never typed by hand)."""
from __future__ import annotations

import json
from pathlib import Path

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
LABEL = {"threshold_100k": "$100k threshold rule", "threshold_50k": "$50k threshold rule", "threshold_25k": "$25k threshold rule",
         "expert_checklist": "Expert rule checklist (no notes)", "money_only": "Money movement only (engine A)",
         "rules_plus_keyword_notes": "Engines A + B + keyword notes", "sentinel": "**Sentinel**",
         "ablation_no_notes": "Sentinel without notes", "ablation_no_sequences": "Sentinel without sequences",
         "ablation_no_money": "Sentinel without money movement", "ablation_no_network": "Sentinel without the mule-account network",
         "ablation_no_memory": "Sentinel without household memory", "with_network": "Sentinel plus the mule-account network (not chosen)",
         "with_memory": "Sentinel plus household memory (not chosen)"}
TYP = {"investment_romance_scam": "Investment, crypto or romance", "tech_support_impersonation": "Tech support / bank impersonation",
       "government_impersonation": "Government impersonation", "silent_account_takeover": "Silent account takeover",
       "grandparent_voice_clone": "Grandparent / voice clone", "trusted_person_theft": "Trusted-person theft"}


def p(m, d=0):
    v = m["value"] if isinstance(m, dict) else m
    return "–" if v is None else f"{v * 100:.{d}f}%"


def ci(m):
    return f"{m['ci95'][0] * 100:.0f}–{m['ci95'][1] * 100:.0f}%" if m.get("ci95") else ""


def render(r: dict, seeds: dict | None) -> str:
    M, MW = r["methods"], r["matched_workload_100k"]
    reader = ("Claude notes reader" if r["meta"]["notes_reader"] == "llm" else
              "keyword notes reader (the score does not use Claude; see What the LLM adds and Limitations)")
    out = [f"Test split: {r['meta']['households']['test']:,} households never seen in training. Notes reader: {reader}. "
           f"95% confidence intervals from household bootstrap. Generated by `make eval readme`.", "",
           f"**Same reviewer workload as the $100k rule** ({MW['weekly_rate'] * 100:.2f}% of households per week):", "",
           "| Method | Cases caught | 95% CI | Caught before money left | Dollars protected | Look-alike false alarms | Precision at 0.5% base rate |",
           "|---|---|---|---|---|---|---|"]
    for k in ("threshold_100k", "expert_checklist", "money_only", "sentinel"):
        m = MW[k]
        out.append(f"| {LABEL[k]} | {p(m['recall'], 1)} | {ci(m['recall'])} | {p(m['caught_before_money_left'], 1)} | "
                   f"{p(m['dollars_protected_share'], 1)} | {p(m['lookalike_false_alarm_rate'], 1)} | {p(m['precision_at_0.5pct_base_rate'], 1)} |")
    out += ["", "**At fixed weekly review budgets** (cases caught, with look-alike false alarms in brackets):", "",
            "| Method | Fixed rule | 0.1% budget | 0.25% budget | 1% budget |", "|---|---|---|---|---|"]
    for k in ("threshold_100k", "threshold_25k"):
        m = M[k]["natural"]
        out.append(f"| {LABEL[k]} (fixed, {m['alerts_per_1k_households_per_week']['value']:.2f} alerts per 1k households a week) | "
                   f"{p(m['recall'])} ({p(m['lookalike_false_alarm_rate'])}) | | | |")
    for k in [k for k in LABEL if k in M and "budgets" in M[k]]:
        b = M[k]["budgets"]
        out.append(f"| {LABEL[k]} | | " + " | ".join(f"{p(b[x]['recall'])} ({p(b[x]['lookalike_false_alarm_rate'])})" for x in ("0.1%", "0.25%", "1%")) + " |")
    s = M["sentinel"]["budgets"]["0.25%"]
    loto = r.get("leave_one_typology_out", {})
    out += ["", "**By scam type** at a 0.25% budget, and with that type held out of training entirely:", "",
            "| Typology | Test cases | Sentinel | Same features, all types seen | Same features, type never seen | $100k rule |",
            "|---|---|---|---|---|---|"]
    for t, name in TYP.items():
        bt = s["by_typology"].get(t, {})
        lo = loto.get(t, {})
        out.append(f"| {name} | {bt.get('n', 0)} | {p(bt.get('recall'))} | {p(lo.get('same_features_trained_on_all_recall', {}).get('0.25%'))} | "
                   f"{p(lo.get('sentinel_recall', {}).get('0.25%'))} | {p(lo.get('threshold_100k_recall'))} |")
    fair = s["fairness_by_age_band"]
    out += ["", "**Calibration:** expected calibration error " + str(r["calibration"]["ece"]) + ". "
            "**Fairness** (false-alarm rate relative to overall, target ≤ 1.25×): "
            + ", ".join(f"ages {k} {v['ratio_to_overall']:.2f}×" for k, v in fair.items()) + ". "
            f"**Speed:** {r['cost']['ms_per_household_scored']} ms per household for all three engines on a laptop."]
    rob = r.get("robustness")
    if rob:
        out += ["", "**Robustness** (same model and thresholds, cases caught at 0.25%): "
                + ", ".join(f"{n} {p(rob[k]['0.25%']['recall'])}" for k, n in
                            [("baseline", "as evaluated"), ("no_notes", "all notes removed"), ("half_notes", "half the notes removed"),
                             ("noisy_account_events", "doubled account-event noise")] if k in rob)
                + f"; coached cover stories {p(rob['coached_cover_story_at_0.25%']['recall'])} (n={rob['coached_cover_story_at_0.25%']['n']})."]
    if seeds:
        sr = seeds["methods"]["sentinel"]["0.25%"]["recall"]
        out += ["", f"**Stability across {len(seeds['seeds'])} independently generated worlds:** Sentinel catches "
                f"{sr['mean'] * 100:.0f}% of cases at 0.25% on average (range {sr['min'] * 100:.0f}–{sr['max'] * 100:.0f}%)."]
        bt = seeds.get("by_typology", {})
        if bt.get("sentinel"):
            out += ["", "By scam type, mean ± sd of cases caught across the worlds:", "",
                    "| Typology | Sentinel at 0.25% | Sentinel at 1% | $100k rule |", "|---|---|---|---|"]
            for t, name in TYP.items():
                cell = lambda d: "–" if not d or d.get("mean") is None else f"{d['mean'] * 100:.0f}% ± {d['sd'] * 100:.0f}"
                out.append(f"| {name} | {cell(bt['sentinel']['0.25%'].get(t))} | {cell(bt['sentinel']['1%'].get(t))} | "
                           f"{cell(bt.get('threshold_100k', {}).get('natural', {}).get(t))} |")
    out += readers_section(r.get("readers")) + v1_section(r) + selection_section(r) + tuning_section(r)
    for f, label in (("results/notes_reader_usage.json", "Notes reader"), ("results/case_agent_usage.json", "Case agent")):
        if Path(f).exists():
            u = json.loads(Path(f).read_text())
            out.append(f"\n**{label} usage:** {json.dumps(u)}")
    return "\n".join(out)


def readers_section(rd: dict | None) -> list[str]:
    """What the LLM adds: keyword reader vs Claude on the same notes, against the planted truth."""
    if not rd:
        return []
    k, c, d, ic = rd["keyword"], rd["claude"], rd["claude_minus_keyword"], rd["injection_controls"]
    out = ["", f"**What the LLM adds** (notes reader on the same {rd['meta']['n_notes']:,} notes, scored against the planted "
           "red-flag categories; read by Claude Haiku through Claude Code subagents with the production prompt, since no API key "
           "was available; see Limitations):", "",
           "| Reader | Precision | Recall | F1 | Macro F1 |", "|---|---|---|---|---|",
           f"| Keyword list | {p(k['micro']['precision'])} | {p(k['micro']['recall'])} | {p(k['micro']['f1'])} | {p(k['macro_f1'])} |",
           f"| Claude | {p(c['micro']['precision'])} | {p(c['micro']['recall'])} | {p(c['micro']['f1'])} | {p(c['macro_f1'])} |",
           "", f"Claude minus keyword, F1: {d['micro_f1']['value'] * 100:+.0f} points (95% CI {ci(d['micro_f1'])}). "
           f"Quotes that were not exact substrings of the note: {rd['quotes']['n_dropped']} of {rd['quotes']['n_quotes']:,}. "]
    pre = ic.get("claude_before_guardrail", {})
    iv, rr = pre.get("injected_vs_control"), pre.get("reread_vs_control")
    line = (f"**Prompt injection** ({ic['n_pairs']} injected notes, each also read with the injection removed): Claude reported "
            f"the injection in {ic['claude']['injection_reported']} and red flags changed in {ic['claude']['flags_changed']}")
    if iv and rr:
        line += (f" (a plain second read of the same notes changes them in {rr['flags_changed']}). Mitigating context is less "
                 f"stable: it changed in {p(iv['mitigating_changed_rate'])} of injected notes, against {p(rr['mitigating_changed_rate'])} "
                 f"on a plain re-read, but injected notes gained mitigating quotes {iv['more_mitigating_quotes']} times and lost them "
                 f"{iv['fewer_mitigating_quotes']} times, so code now ignores mitigating context in any note with an injection "
                 f"(risk-lowering context added by an injection after that rule: {ic['claude']['mitigating_added_by_injection']})")
    return out + [line + "."]


def v1_section(r: dict) -> list[str]:
    """Frozen v1 (before mule accounts, memory and tuning) against now, on the same households."""
    p1 = Path("results/v1_metrics.json")
    if not p1.exists():
        return []
    v1 = json.loads(p1.read_text())
    rows = [("Cases caught, same workload as $100k rule", lambda m: m["matched_workload_100k"]["sentinel"]["recall"]),
            ("Cases caught at 0.25%", lambda m: m["methods"]["sentinel"]["budgets"]["0.25%"]["recall"]),
            ("Caught before money left at 0.25%", lambda m: m["methods"]["sentinel"]["budgets"]["0.25%"]["caught_before_money_left"]),
            ("Look-alike false alarms at 0.25%", lambda m: m["methods"]["sentinel"]["budgets"]["0.25%"]["lookalike_false_alarm_rate"]),
            ("$100k rule, cases caught", lambda m: m["methods"]["threshold_100k"]["natural"]["recall"])]
    out = ["", "**Before and after the finals changes** (v1 was frozen in `results/v1_metrics.json` before the world changed; the "
           "only change to the world is the destination-account column, drawn from a separate random stream, so every v1 record "
           "is identical and the baselines were re-run on it):", "", "| | v1 | Now |", "|---|---|---|"]
    out += [f"| {name} | {p(f(v1), 1)} | {p(f(r), 1)} |" for name, f in rows]
    return out


def selection_section(r: dict) -> list[str]:
    sel = r.get("selection")
    if not sel:
        return []
    ch = sel["chosen"]
    out = ["", f"**Which model is Sentinel** was decided on validation only ({sel['selected_by']}; test untouched). "
           "This step was added after a test run showed the finals additions did not beat v1; the candidates and the rule were "
           f"fixed before it ran. Chosen: **{ch['feature_set']}**, {ch['settings']} settings.", "",
           "| Feature blocks | Settings | Validation recall at 0.25% | Validation look-alike false alarms |", "|---|---|---|---|"]
    out += [f"| {c['features']} | {c['settings']} | {p(c['recall_0.25%'], 1)} | {p(c['false_alarms_0.25%'], 1)} |"
            for c in sorted(sel["candidates"], key=lambda c: -c["recall_0.25%"])]
    return out


def tuning_section(r: dict) -> list[str]:
    t = r.get("tuning")
    if not t or not t.get("configs"):
        return []
    ch = t["chosen"]
    best = lambda obj: max((c["val"]["0.25%"] for c in t["configs"] if c["objective"] == obj), key=lambda v: v["recall"], default=None)
    rk, bn = best("lambdarank"), best("binary")
    line = (f"**Settings search** (`eval/tune.py`, world 0's validation split only): {len(t['configs'])} configurations; best was "
            f"`{ch['objective']}` with `{json.dumps(ch['params'])}`.")
    if rk and bn:
        line += (f" LightGBM's ranking objective, grouped by week, reached {p(rk['recall'], 1)} validation recall at 0.25% "
                 f"against {p(bn['recall'], 1)} for the best binary model.")
    sel = r.get("selection")
    if sel:
        line += (f" That tuned config then lost to LightGBM's default settings in the 5-world validation selection above, for every "
                 f"feature set, so Sentinel uses the defaults: one world's validation split (about 80 cases) was too small to tune on.")
    return ["", line]


def main():
    r = json.loads(Path("results/metrics.json").read_text())
    seeds = json.loads(Path("results/seeds.json").read_text()) if Path("results/seeds.json").exists() else None
    readme = Path("README.md").read_text(encoding="utf-8")
    i, j = readme.index(START) + len(START), readme.index(END)
    Path("README.md").write_text(readme[:i] + "\n" + render(r, seeds) + "\n" + readme[j:], encoding="utf-8")
    print("README.md results updated")


if __name__ == "__main__":
    main()
